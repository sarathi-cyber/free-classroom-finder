import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseSearch,evaluate,dayOf,minute} from './dist/engine.mjs';
const data=JSON.parse(fs.readFileSync(new URL('./dist/data.json',import.meta.url)));
const base={date:'2026-09-28',time:'11:00',duration:60,floor:'all',ac:'any',people:''};
const room=id=>data.rooms.find(r=>r.id===id);
const check=(id,q)=>evaluate(room(id),data.events,{...base,...q});
assert.equal(check('518',{time:'12:30',duration:50}).match,true,'Shared room has lunch gap');
assert.equal(check('518',{time:'12:30',duration:51}).match,false,'A future class prevents a too-long stay');
assert.equal(check('518',{time:'13:20',duration:60}).current[0].section,'III ECE B','Both sections contribute occupancy');
assert.equal(check('225',{time:'09:50',duration:60}).match,true,'Ending exactly at next class is allowed');
assert.equal(check('225',{time:'09:50',duration:61}).match,false,'One minute overlap is rejected');
assert.equal(check('225',{time:'16:30',duration:30}).known,false,'Outside covered day remains unknown');
assert.equal(check('225',{date:'2026-10-03'}).known,false,'Weekend is unknown');
assert.equal(check('225',{date:'2026-02-30'}).known,false,'Invalid date is unknown');
assert.equal(check('225',{time:'13:20',ac:'yes'}).match,false,'Unknown AC is not a match');
assert.equal(check('225',{time:'13:20',floor:'0'}).match,false,'Unknown floor is not a match');
assert.equal(check('225',{time:'13:20',people:6}).match,false,'Unknown capacity is not a match');
assert.equal(evaluate({...room('225'),floor:0,ac:true,capacity:8},data.events,{...base,time:'13:20',floor:'0',ac:'yes',people:6}).match,true,'Confirmed attributes permit exact match');
assert.equal(check('107',{time:'15:10',duration:30}).match,false,'Lab is not a study-room recommendation');
assert.ok(check('107',{time:'13:20',duration:30}).current.length,'Split lab blocks 107');
assert.ok(check('309',{time:'13:20',duration:30}).current.length,'Split lab blocks 309');
const p=parseSearch('I need an AC room on the ground floor for me and my team for the next 2 hours',base).query;
assert.equal(p.ac,'yes');assert.equal(p.floor,'0');assert.equal(p.duration,120);assert.equal(p.people,'');
assert.equal(parseSearch('non AC room for one and a half hours',base).query.duration,90);
assert.equal(parseSearch('non AC room for one and a half hours',base).query.ac,'no');
assert.equal(parseSearch('a room one flight up for thirty minutes',base).query.floor,'1','Trained intent classifier handles floor paraphrase');
assert.equal(parseSearch('room on the lowest level for 1 hour',base).query.floor,'0');
assert.equal(parseSearch('first floor for ninety minutes for 6 people',base).query.people,6);
assert.equal(parseSearch('a room on any floor',base).query.floor,'all');
assert.equal(parseSearch('Any room tomorrow at 11 am for 1 hour',base).query.time,'11:00');
assert.equal(parseSearch('room at 1 pm until 3 pm',base).query.duration,120);
assert.throws(()=>parseSearch('room at 14:99',base));assert.throws(()=>parseSearch('a room with a projector',base));assert.throws(()=>parseSearch('room for 0 hours',base));
assert.equal(minute('25:00'),NaN);assert.equal(dayOf('2026-09-28'),1);
assert.equal(data.sources.length,10);assert.equal(data.sources.filter(s=>s.active).length,9);
console.log('Passed: overlaps, boundaries, shared rooms, source counts, unknown metadata, weekends, split labs, and natural-language constraints.');
